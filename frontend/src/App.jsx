import { useEffect, useState } from 'react';

const API = 'http://127.0.0.1:5000/api';

const starterMissions = [
  {
    title: 'Notice the tiny things',
    result: '1. Find a safe place to pause outdoors.\n2. Notice three different leaf shapes without picking them.\n3. Listen quietly for one minute.\n\nReflection: What did you notice only after slowing down?'
  },
  {
    title: 'A five-minute sky break',
    result: '1. Look up from a safe spot.\n2. Notice the shapes and movement of clouds.\n3. Find one subtle change in the light or weather.\n\nReflection: What changed while you were watching?'
  },
  {
    title: 'Listen to your surroundings',
    result: '1. Stand somewhere safe and still.\n2. Identify three different sounds.\n3. Try to tell which sounds are near and which are far away.\n\nReflection: Which sound had you not noticed before?'
  }
];

export default function App() {
  const [interest, setInterest] = useState('plants and leaves');
  const [duration, setDuration] = useState('10 minutes');
  const [question, setQuestion] = useState('');
  const [mission, setMission] = useState(null);
  const [answer, setAnswer] = useState('');
  const [loading, setLoading] = useState(false);
  const [status, setStatus] = useState('');
  const [journal, setJournal] = useState(() => {
    try { return JSON.parse(localStorage.getItem('trailmate-journal') || '[]'); }
    catch { return []; }
  });
  const [reflection, setReflection] = useState('');

  useEffect(() => {
    localStorage.setItem('trailmate-journal', JSON.stringify(journal));
  }, [journal]);

  async function generateMission() {
    setLoading(true);
    setStatus('');
    setAnswer('');
    try {
      const res = await fetch(`${API}/mission`, {
        method: 'POST',
        headers: { 'Content-Type': 'application/json' },
        body: JSON.stringify({ interest, duration })
      });
      const data = await res.json();
      if (!res.ok) throw new Error(data.error || 'Could not generate a mission.');
      setMission({ title: 'Your TrailMate mission', result: data.result });
      setStatus('Generated by your local model.');
    } catch (err) {
      const fallback = starterMissions[Math.floor(Math.random() * starterMissions.length)];
      setMission(fallback);
      setStatus('Local AI unavailable — showing a built-in sample mission. Start the backend and Ollama for AI-generated missions.');
    } finally {
      setLoading(false);
    }
  }

  async function askNature(e) {
    e.preventDefault();
    if (!question.trim()) return;
    setLoading(true);
    setAnswer('');
    try {
      const res = await fetch(`${API}/ask`, {
        method: 'POST',
        headers: { 'Content-Type': 'application/json' },
        body: JSON.stringify({ question })
      });
      const data = await res.json();
      if (!res.ok) throw new Error(data.error || 'Could not get an answer.');
      setAnswer(data.result);
    } catch {
      setAnswer('The local AI is not available right now. Start Ollama and the Flask backend, then try again.');
    } finally {
      setLoading(false);
    }
  }

  function saveReflection() {
    if (!reflection.trim()) return;
    setJournal(prev => [{ text: reflection.trim(), date: new Date().toLocaleDateString() }, ...prev]);
    setReflection('');
  }

  return (
    <main className="page">
      <nav className="nav">
        <a className="brand" href="#top"><span className="brand-icon">✳</span> trailmate<span className="brand-ai">AI</span></a>
        <span className="nav-note">A little less scrolling. A little more noticing.</span>
      </nav>

      <section className="hero" id="top">
        <div className="hero-copy">
          <p className="eyebrow"><span className="dot" /> YOUR INVITATION OUTSIDE</p>
          <h1>The world is<br /><em>still loading.</em></h1>
          <p className="hero-text">Trade another scroll for a small adventure. Get a nature mission, step outside, and notice something new.</p>
          <a className="button button-dark" href="#mission">Find your mission <span>↗</span></a>
        </div>
        <div className="hero-art" aria-label="Illustration of hills, sun and trees">
          <div className="sun" />
          <div className="hill hill-back" />
          <div className="hill hill-front" />
          <div className="tree tree-one"><i /><b /></div>
          <div className="tree tree-two"><i /><b /></div>
          <span className="art-label">GO OUTSIDE<br />COME BACK CURIOUS.</span>
        </div>
      </section>

      <section className="section mission-section" id="mission">
        <div className="section-heading">
          <p className="eyebrow">01 / YOUR NEXT LITTLE ADVENTURE</p>
          <h2>Make room for <em>wonder.</em></h2>
          <p>Tell TrailMate what you want to explore. Your local AI will make a tiny mission for your next walk.</p>
        </div>
        <div className="mission-grid">
          <div className="form-card">
            <label htmlFor="interest">What are you curious about?</label>
            <select id="interest" value={interest} onChange={e => setInterest(e.target.value)}>
              <option>plants and leaves</option><option>birds and sounds</option>
              <option>clouds and sky</option><option>insects from a safe distance</option>
              <option>colors and textures</option><option>gardening</option>
            </select>
            <label htmlFor="duration">How much time do you have?</label>
            <div className="duration-options">
              {['5 minutes', '10 minutes', '20 minutes'].map(d =>
                <button key={d} className={duration === d ? 'duration active' : 'duration'} onClick={() => setDuration(d)}>{d}</button>
              )}
            </div>
            <button className="button button-green full" onClick={generateMission} disabled={loading}>
              {loading ? 'Thinking locally…' : 'Generate my mission'} <span>↗</span>
            </button>
            <p className="small-note">Powered by a local Gemma model through Ollama.</p>
          </div>
          <div className="result-card">
            <div className="result-top"><span>✳ FIELD NOTE</span><span>NO. 001</span></div>
            {mission ? <>
              <h3>{mission.title}</h3>
              <p className="result-text">{mission.result}</p>
              {status && <p className="status">{status}</p>}
            </> : <>
              <div className="empty-icon">↗</div>
              <h3>Your next mission<br />is waiting.</h3>
              <p className="muted">Generate a mission, read it once, then put your phone away and go explore.</p>
            </>}
            <div className="result-bottom">OBSERVE GENTLY · LEAVE NO TRACE</div>
          </div>
        </div>
      </section>

      <section className="ask-section">
        <div>
          <p className="eyebrow">02 / STAY CURIOUS</p>
          <h2>Wondering about<br /><em>something outside?</em></h2>
          <p className="muted">Ask a question before or after your walk. Keep a safe distance from wildlife and never eat unknown plants or fungi.</p>
        </div>
        <form className="ask-form" onSubmit={askNature}>
          <label htmlFor="question">Ask your nature question</label>
          <textarea id="question" value={question} onChange={e => setQuestion(e.target.value)} placeholder="Why do some leaves change color?" rows="3" />
          <button className="button button-dark" disabled={loading}>Ask TrailMate <span>↗</span></button>
          {answer && <div className="answer-box"><strong>TRAILMATE SAYS</strong><p>{answer}</p></div>}
        </form>
      </section>

      <section className="section journal-section">
        <div className="section-heading">
          <p className="eyebrow">03 / BRING BACK A MEMORY</p>
          <h2>Small things are <em>big things.</em></h2>
          <p>When you return, write down one thing you noticed. Your notes stay in this browser.</p>
        </div>
        <div className="journal">
          <textarea value={reflection} onChange={e => setReflection(e.target.value)} placeholder="Today outside, I noticed…" rows="3" />
          <button className="button button-green" onClick={saveReflection}>Save field note <span>↗</span></button>
        </div>
        {journal.length > 0 && <div className="journal-list">{journal.map((entry, i) =>
          <article className="journal-entry" key={`${entry.date}-${i}`}><span>{entry.date}</span><p>{entry.text}</p></article>
        )}</div>}
      </section>

      <footer>
        <a className="brand" href="#top"><span className="brand-icon">✳</span> trailmate<span className="brand-ai">AI</span></a>
        <p>Made for the world beyond the screen.</p>
        <span className="footer-tag">OPEN MODELS. OPEN AIR. 🌱</span>
      </footer>
    </main>
  );
}
